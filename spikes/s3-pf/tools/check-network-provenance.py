#!/usr/bin/env python3
"""Bounded own-loopback host diagnostic. Default dry-run; no signing or system mutation.
Requires explicitly supplied already-signed hardened binaries. Preserves every run/prefix.
"""
import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import selectors
import shutil
import socket
import subprocess
import time
import uuid


def encode(value):
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode()


def save(path, value):
    data = value if isinstance(value, bytes) else encode(value)
    with path.open("xb") as stream:
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())


def run(command, timeout=5):
    result = subprocess.run(command, capture_output=True, timeout=timeout, check=False)
    return result.returncode, result.stdout, result.stderr


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sender", required=True, type=Path)
    parser.add_argument("--counterpart", required=True, type=Path)
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    if not args.apply:
        print("DRY-RUN: verify supplied hardened binaries; preregister names-free own identity and fresh flows; run bounded exact 127.0.0.1/::1 ephemeral fixtures; retain raw in new /private/tmp directory. No network or files created.")
        return 0
    for binary in [args.sender, args.counterpart]:
        assert binary.is_absolute() and binary.is_file() and not binary.is_symlink()
        rc, _, error = run(["/usr/bin/codesign", "--verify", "--strict", str(binary)])
        assert rc == 0, error.decode()
    root = Path("/private/tmp/sanjbox-network-validation-" + str(uuid.uuid4()))
    root.mkdir(mode=0o700)
    print(root, flush=True)
    expected = {}
    for role, binary in [("sender", args.sender), ("receiver", args.counterpart)]:
        rc, out, err = run([str(binary), "provenance-identity"])
        save(root / (role + "-identity.stdout"), out)
        save(root / (role + "-identity.stderr"), err)
        assert rc == 0, err.decode()
        expected[role] = json.loads(out)
        assert expected[role]["signature"]["valid"] and expected[role]["signature"]["hardenedRuntime"]
        assert expected[role]["signature"]["getTaskAllowAbsent"]
        save(root / ("expect-" + role + ".json"), expected[role])
    # All flow IDs and challenges are generated by the native prepare command before any socket.
    cases = []
    for label, transport, host, kind in [
        ("tcp-v4", "tcp", "127.0.0.1", "native"), ("udp-v4", "udp", "127.0.0.1", "native"),
        ("tcp-v6", "tcp", "::1", "native"), ("udp-v6", "udp", "::1", "native"),
        ("udp-adversarial", "udp", "127.0.0.1", "pythonFixture"),
        ("tcp-adversarial", "tcp", "127.0.0.1", "pythonFixture"),
        ("contact-limit", "udp", "127.0.0.1", "pythonFixture"),
        ("interrupted-prefix", "tcp", "127.0.0.1", "pythonFixture"),
        ("refused-connect", "tcp", "127.0.0.1", "native"),
    ]:
        rc, out, err = run([str(args.sender), "provenance-prepare", "--run-id", str(uuid.uuid4())])
        assert rc == 0, err.decode()
        flow = json.loads(out)
        registration = dict(schemaVersion=1, scope="hostDiagnostic", flow=flow, transport=transport,
                            endpoint=dict(host=host, port=0), controlledTarget=True,
                            durationMilliseconds=1500, maximumContacts=2 if label == "contact-limit" else 16)
        cases.append(dict(label=label, actor=kind, registration=registration))
    preregistration = dict(schemaVersion=1, kind="hostDiagnosticNotL4", preparedUTC=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        expectations=expected, cases=cases, assertions=["four native flows bind actual exact tuples and raw bytes",
        "zero/malformed/wrong nonce/foreign run/replay remain contacts", "TCP split reassembles; stalled read is incomplete",
        "contact budget is incomplete", "interrupted TCP retains prefix without terminal", "refused native attempt retains zero local acceptance",
        "identity/signature before missing target; dry-run no socket/output; no reused output"],
        limitations="No peer authentication, packet capture, cross-zone isolation, S1, S3/S3b or L4 verdict; Python injection is a fixture actor.")
    save(root / "preregistration.json", preregistration)
    results = []
    retained = []

    def command(binary, role, file, apply=True, expectation=None):
        return [str(binary), "provenance", "--expect", str(expectation or root / ("expect-" + role + ".json")), "--input", str(file)] + (["--apply"] if apply else [])

    def collect(case_dir, path):
        path = Path(path)
        assert path.parent == Path("/private/tmp") and path.name.startswith("sanjbox-network-") and not path.is_symlink()
        retained.append(str(path))
        destination = case_dir / path.name
        shutil.copytree(path, destination)
        events = [json.loads(line) for line in (destination / "events.jsonl").read_bytes().splitlines()]
        for event in events:
            assert event["format"] == "sanjboxNetworkProvenanceV1"
            if "rawFile" in event:
                raw = (destination / event["rawFile"]).read_bytes()
                assert hashlib.sha256(raw).hexdigest() == event["rawSHA256"]
                if "bytes" in event:
                    assert len(raw) == event["bytes"]
        return events

    def wait_ready(process):
        with selectors.DefaultSelector() as selector:
            selector.register(process.stdout, selectors.EVENT_READ)
            assert selector.select(5), "receiver readiness deadline"
            line = process.stdout.readline()
        assert line, "receiver ended before readiness"
        return line, json.loads(line)

    # Negative preflight must fail before opening a missing target file (not merely before socket).
    changed = copy.deepcopy(expected["sender"])
    changed["identity"]["auditSessionID"] += 1
    bad = root / "expect-wrong.json"
    save(bad, changed)
    rc, out, err = run(command(args.sender, "sender", root / "probe-missing.json", expectation=bad))
    save(root / "wrong-identity.stderr", err)
    assert rc == 2 and b"identity/session" in err and b"control file" not in err
    results.append(dict(check="identity-before-target", passed=True))
    changed = copy.deepcopy(expected["sender"])
    changed["signature"]["codeHash"] = "0" * 40
    bad = root / "expect-signature.json"
    save(bad, changed)
    rc, out, err = run(command(args.sender, "sender", root / "probe-missing.json", expectation=bad))
    save(root / "wrong-signature.stderr", err)
    assert rc == 2 and b"signature mismatch" in err
    results.append(dict(check="signature-before-target", passed=True))

    for case in cases:
        label = case["label"]
        directory = root / label
        directory.mkdir(mode=0o700)
        registration = case["registration"]
        config = directory / "probe-receiver.json"
        save(config, registration)
        frame = ("SANJBOX-NETWORK-PROVENANCE-V1|" + registration["flow"]["runID"].upper() + "|" + registration["flow"]["flowID"].upper() + "|" + registration["flow"]["challenge"] + "\n").encode()
        receiver = None
        own_socket = None
        try:
            if label == "refused-connect":
                own_socket = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
                own_socket.bind(("127.0.0.1", 0))  # Exclusively owned, deliberately not listening.
                ready = dict(host="127.0.0.1", port=str(own_socket.getsockname()[1]))
            else:
                receiver = subprocess.Popen(command(args.counterpart, "receiver", config), stdout=subprocess.PIPE, stderr=subprocess.PIPE)
                first, ready = wait_ready(receiver)
            target = (ready["host"], int(ready["port"]))
            assert target[0] in ["127.0.0.1", "::1"] and target[1] >= 1024
            sender_registration = copy.deepcopy(registration)
            sender_registration["endpoint"]["port"] = target[1]
            sender_file = directory / "probe-sender.json"
            save(sender_file, sender_registration)  # Exact allocated endpoint sealed before sender attempt.
            if case["actor"] == "native":
                rc, out, err = run(command(args.sender, "sender", sender_file, apply=False))
                save(directory / "dry-run.stdout", out)
                assert rc == 0 and json.loads(out)["status"] == "dryRun"
                rc, out, err = run(command(args.sender, "sender", sender_file))
                save(directory / "sender.stdout", out); save(directory / "sender.stderr", err)
                assert rc == (3 if label == "refused-connect" else 0), err.decode()
                sender_events = collect(directory, json.loads(out)["output"])
                assert sender_events[0]["kind"] == "registered"
                assert sender_events[-1]["kind"] == "attemptEnded"
                if label == "refused-connect":
                    assert sender_events[-1]["localKernelAcceptedBytes"] == 0
                    assert "remote" not in sender_events[-1]
                    assert not sender_events[-1]["operationFinished"]
                else:
                    assert sender_events[-1]["localKernelAcceptedBytes"] == len(frame)
                rc, again, error = run(command(args.sender, "sender", sender_file))
                save(directory / "reuse.stderr", error)
                assert rc == 2 and b"exclusive run output refused" in error
            elif label in ["udp-adversarial", "contact-limit"]:
                with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as injector:
                    injector.bind(("127.0.0.1", 0))
                    injector.settimeout(1)
                    wrong = frame[:-2] + (b"0" if frame[-2:-1] != b"0" else b"1") + b"\n"
                    foreign = frame.replace(registration["flow"]["runID"].upper().encode(), str(uuid.uuid4()).upper().encode())
                    payloads = [b"", wrong, frame, frame, foreign, b"malformed", b"x" * 5000] if label == "udp-adversarial" else [b"", b"", b""]
                    for i, payload in enumerate(payloads):
                        save(directory / ("injected-" + str(i) + ".bin"), payload)
                        injector.sendto(payload, target)
                    save(directory / "injection.json", dict(actor="pythonFixture", local=injector.getsockname(), remote=target, payloadCount=len(payloads)))
            else:
                injector = socket.create_connection(target, timeout=1)
                own_socket = injector
                if label == "interrupted-prefix":
                    injector.sendall(frame[:35])
                    raw = Path(ready["output"]) / "received-1.bin"
                    deadline = time.monotonic() + 1
                    while not raw.exists() or raw.stat().st_size < 35:
                        assert time.monotonic() < deadline
                        time.sleep(.005)
                    receiver.terminate()  # Only the child owned by this Popen; preserve interrupted journal.
                else:
                    injector.sendall(frame[:35]); time.sleep(.02); injector.sendall(frame[35:]); injector.close(); own_socket = None
                    with socket.create_connection(target, timeout=1):
                        pass  # Zero-byte TCP contact.
                    own_socket = socket.create_connection(target, timeout=1)
                    own_socket.sendall(b"held-prefix")  # Deliberately exceeds the 500ms per-contact read deadline.
                save(directory / "injection.json", dict(actor="pythonFixture", remote=target, kind=label))
            if receiver:
                out, err = receiver.communicate(timeout=5)
                save(directory / "receiver.stdout", first + out); save(directory / "receiver.stderr", err)
                events = collect(directory, ready["output"])
                received = [event for event in events if event["kind"] in ["closed", "datagram"]]
                if case["actor"] == "native":
                    assert receiver.returncode == 0 and len(received) == 1
                    event = received[0]
                    assert event["matchesRegisteredPayload"] and not event["repeatedRegisteredPayload"]
                    assert event["rawSHA256"] == hashlib.sha256(frame).hexdigest()
                    assert event["local"] == sender_events[-1]["remote"]
                    assert event["remote"] == sender_events[-1]["local"]
                elif label == "udp-adversarial":
                    assert receiver.returncode == 3 and len(received) == 7
                    assert received[0]["bytes"] == 0 and not received[0]["matchesRegisteredPayload"]
                    assert not received[1]["matchesRegisteredPayload"]
                    assert received[2]["matchesRegisteredPayload"] and received[3]["repeatedRegisteredPayload"]
                    assert received[4]["payloadClaims"]["runID"] != received[4]["runID"]
                    assert "payloadClaims" not in received[5] and received[6]["rawTruncated"]
                elif label == "tcp-adversarial":
                    assert receiver.returncode == 3 and len(received) == 3
                    assert received[0]["matchesRegisteredPayload"] and received[1]["bytes"] == 0
                    assert received[2]["reason"] == "readDeadline" and received[2]["bytes"] == len(b"held-prefix")
                elif label == "contact-limit":
                    assert receiver.returncode == 3 and len(received) == 2 and events[-1]["reason"] == "contactLimit"
                else:
                    assert receiver.returncode == -15
                    assert not any(event["kind"] == "receiverStopped" for event in events)
                    assert (Path(ready["output"]) / "received-1.bin").read_bytes() == frame[:35]
            results.append(dict(check=label, passed=True, runID=registration["flow"]["runID"]))
        finally:
            if own_socket:
                own_socket.close()
            if receiver and receiver.poll() is None:
                receiver.kill()
                receiver.communicate(timeout=5)
    save(root / "results.json", dict(results=results, retainedProducerOutputs=retained,
        cleanup="All owned subprocesses reaped and sockets closed; immutable raw directories retained. No capture completeness or isolation verdict."))
    manifest = {}
    for path in sorted(root.rglob("*")):
        if path.is_file():
            manifest[str(path.relative_to(root))] = hashlib.sha256(path.read_bytes()).hexdigest()
    save(root / "manifest.json", manifest)
    print(json.dumps(dict(checks=len(results), passed=True, output=str(root))), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
